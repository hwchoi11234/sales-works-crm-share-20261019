import assert from 'node:assert/strict';
import { registerHooks } from 'node:module';
registerHooks({ resolve(s, c, next) { return next(s === './lead-fields' && c.parentURL?.endsWith('sheet-intake.ts') ? './lead-fields.ts' : s, c); } });
const { parseSheetCsv, prepareSheetRows, sheetTimestamp } = await import('../lib/sheet-intake.ts');
assert.deepEqual(parseSheetCsv('\uFEFFa,b\r\n"hello, world","a""b\nline"\r\n'), [['a','b'], ['hello, world','a"b\nline']]);
assert.throws(() => parseSheetCsv('a,b\n"bad'));
assert.equal(sheetTimestamp('2026-10-12 12:55:06'), '2026-10-12T03:55:06.000Z');
assert.equal(sheetTimestamp('2026-10-12T03:55:06Z'), '2026-10-12T03:55:06.000Z');
assert.throws(() => sheetTimestamp('2026-02-30 12:55:06'));
assert.throws(() => sheetTimestamp('2026-10-12 25:55:06'));
const csv = '응답 일시,캠페인 ID,광고그룹 ID,소재 ID,이름,연락처,창업 희망 지역을 입력해 주세요.\n2026-10-12 12:55:06,1,2,3,샘플,+82 10-1234-5678,서울\ninvalid,1,2,3,샘플,01012345678,서울';
const p = prepareSheetRows(csv);
assert.equal(p.valid.length, 1); assert.equal(p.invalid.length, 1); assert.equal(p.invalid[0].rowNumber, 3);
assert.equal(p.valid[0].phone, '01012345678'); assert.equal(p.valid[0].metaAutoPhone, '');
assert.equal(p.valid[0].sourceReceivedAt, '2026-10-12T03:55:06.000Z');
assert.equal(p.valid[0].raw['연락처'], '+82 10-1234-5678');
assert.equal(p.missingAutoPhone, true); assert.equal(p.platformConfigured, true);
const optional = '접수일자,이름,연락처,자동입력 연락처,플랫폼,창업희망지역\n2026-10-12 12:55:06,샘플,01012345678,+821099998888,instagram,서울';
const opt = prepareSheetRows(optional);
assert.equal(opt.valid[0].metaAutoPhone, '+821099998888'); assert.equal(opt.valid[0].platform, 'instagram');
assert.equal(opt.missingAutoPhone, false);
assert.equal(opt.valid[0].eventKey, prepareSheetRows(optional + '\n').valid[0].eventKey);
assert.throws(() => prepareSheetRows('접수일자,이름,연락처,창업희망지역,창업 희망지역\n2026-10-12,샘플,01012345678,서울,서울'));
console.log('Sheet source mapping, dates, raw preservation and validation passed');
